import { Box, Button, Flex, Stack, Text, useToast } from "@chakra-ui/react";
import { LuBookOpen, LuSparkles } from "react-icons/lu";
import { EmptyState, Pill, Segmented } from "@/components/ui";
import { getApiErrorMessage } from "@/lib/api";
import { useGenerateLegGuide } from "@/modules/itinerary/hooks/useItinerary";
import { DestinationGuidePanel } from "@/modules/itinerary/components/DestinationGuidePanel";
import type { Trip } from "@/modules/trips/types/trip.types";
import type { TripLeg } from "@/modules/trips/types/trip-leg.types";
import { getEffectiveLegs } from "@/modules/trips/utils/trip-leg.utils";

interface LegExplorePanelProps {
  trip: Trip;
  leg: TripLeg;
  /** Switch city from the segmented control (hidden when omitted or single-city). */
  onCityChange?: (legId: string) => void;
}

/**
 * The Guide tab: the AI local guide for one city (specialties, local food, markets & what to buy,
 * festivals, tips) with generate / regenerate. Vehicle rentals now live on the Stays tab.
 */
export function LegExplorePanel({ trip, leg, onCityChange }: LegExplorePanelProps) {
  const toast = useToast();
  const generateGuide = useGenerateLegGuide(trip.id);
  const hasGuide = Boolean(leg.destinationBrief);
  const legs = getEffectiveLegs(trip);
  const city = leg.name || leg.baseCity;

  const handleGenerateGuide = async () => {
    try {
      await generateGuide.mutateAsync(leg.id);
      toast({ title: "Local guide generated", status: "success" });
    } catch (err) {
      toast({ title: getApiErrorMessage(err), status: "error" });
    }
  };

  return (
    <Stack spacing={4}>
      <Flex justify="space-between" align="center" gap={3} flexWrap="wrap">
        <Flex align="center" gap="10px" flexWrap="wrap">
          {onCityChange && legs.length > 1 && (
            <Segmented value={leg.id} onChange={onCityChange} aria-label="City" options={legs.map((l) => ({ value: l.id, label: l.name || l.baseCity }))} />
          )}
          <Pill tone="accent" icon={LuSparkles}>
            AI guide
          </Pill>
        </Flex>
        {hasGuide && (
          <Flex align="center" gap={2} flexWrap="wrap">
            <Text fontSize="12px" color="tx3">
              Generated by AI · verify details locally
            </Text>
            <Button variant="ai" leftIcon={<LuSparkles />} onClick={() => void handleGenerateGuide()} isLoading={generateGuide.isPending} loadingText="Regenerating…">
              Regenerate
            </Button>
          </Flex>
        )}
      </Flex>

      {hasGuide ? (
        <DestinationGuidePanel legs={[{ leg, brief: leg.destinationBrief }]} />
      ) : (
        <Box bg="sf" borderWidth="1px" borderColor="ln" borderRadius="xl">
          <EmptyState
            icon={LuBookOpen}
            title={`A local guide for ${city}`}
            text="Specialties, local food, markets and what to buy, festivals during your dates, and tips — generated by AI for this city."
            action={
              <Button variant="ai" leftIcon={<LuSparkles />} onClick={() => void handleGenerateGuide()} isLoading={generateGuide.isPending} loadingText="Generating…">
                Generate local guide
              </Button>
            }
          />
        </Box>
      )}
    </Stack>
  );
}
